/**
 * 获取知识分类列表
 */
export function getCategories(): { key: KnowledgeCategory; name: string; icon: string }[] {
  return CATEGORIES
}

/**
 * 获取文章列表（可按分类筛选）
 */
export function getArticles(category?: KnowledgeCategory): KnowledgeArticle[] {
  if (category) {
    return ARTICLES.filter((a) => a.category === category)
  }
  return ARTICLES
}

/**
 * 获取文章详情
 */
export function getArticleById(id: string): KnowledgeArticle | null {
  return ARTICLES.find((a) => a.articleId === id) || null
}

/**
 * 搜索文章
 */
export function searchArticles(keyword: string): KnowledgeArticle[] {
  if (!keyword.trim()) return ARTICLES

  const kw = keyword.toLowerCase()
  return ARTICLES.filter((a) =>
    a.title.toLowerCase().includes(kw) ||
    a.summary.toLowerCase().includes(kw) ||
    a.tags.some((t) => t.toLowerCase().includes(kw)) ||
    a.content.toLowerCase().includes(kw)
  )
}
